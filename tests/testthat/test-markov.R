testthat::test_that("transition validation rejects impossible matrices", {
  testthat::expect_error(validate_transition(matrix(c(-.1,1.1,.5,.5),2,byrow=TRUE)))
  testthat::expect_error(validate_transition(diag(2)*.9))
  testthat::expect_error(base_transition(50))
})
testthat::test_that("fleet and probabilities are conserved", {
  p<-scenario_transition(mode="maintenance")
  path<-evolve(p,c(100,50,50,0),40)
  testthat::expect_equal(rowSums(path),rep(200,41))
  testthat::expect_true(all(path>=0))
  mc<-simulate_fleet(p,c(100,50,50,0),40)
  testthat::expect_equal(rowSums(mc),rep(200,41))
  testthat::expect_identical(mc,simulate_fleet(p,c(100,50,50,0),40))
})
testthat::test_that("academic absorbing result is exactly twenty trips", {
  p<-scenario_transition(mode="absorbing")
  testthat::expect_equal(unname(absorption_expectation(p)),rep(20,3))
  testthat::expect_equal(unname(stationary_distribution(p)),c(0,0,0,1))
  testthat::expect_null(absorption_expectation(scenario_transition(mode="absorbing",failure=0)))
})
testthat::test_that("stationary solutions and repair boundaries are handled", {
  p<-scenario_transition(mode="maintenance")
  pi<-stationary_distribution(p)
  testthat::expect_equal(as.numeric(pi %*% p),as.numeric(pi),tolerance=1e-8)
  testthat::expect_null(stationary_distribution(diag(3)))
  testthat::expect_equal(scenario_transition(mode="maintenance",repair=0),scenario_transition(mode="absorbing"))
  testthat::expect_equal(sum(evolve(p,c(100,50,50,0),500)[501,1:3])/200,.25/(.25+.05),tolerance=1e-6)
})
testthat::test_that("Monte Carlo approaches the analytic expectation", {
  p<-base_transition();initial<-c(100000,0,0)
  theory<-evolve(p,initial,10);simulation<-simulate_fleet(p,initial,10)
  testthat::expect_lt(max(abs(theory[11,]-simulation[11,]))/sum(initial),.01)
})
testthat::test_that("cost accounting and invalid inputs are explicit", {
  p<-scenario_transition(mode="absorbing",failure=1)
  path<-evolve(p,c(10,0,0,0),2)
  cost<-scenario_costs(p,path,trip_cost=.5,failure_cost=50)
  testthat::expect_equal(cost$total,505)
  testthat::expect_error(evolve(p,c(-1,2,3,4)))
  testthat::expect_error(evolve(p,c(1,2,3,4),1.5))
  testthat::expect_error(scenario_costs(p,path,trip_cost=-1))
})
